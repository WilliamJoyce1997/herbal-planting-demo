import { expect, test } from '@playwright/test'

test('地块新增、编辑、查询、排序、删除和关联保护', async ({page}) => {
  await page.goto('/#/admin/plots')
  const mapZone=page.getByRole('button',{name:'A-01 地块详情'})
  const polygon=mapZone.locator('polygon')
  const points=await polygon.getAttribute('points')
  await page.getByLabel('地块搜索').fill('A-01')
  await page.getByRole('button',{name:'查询',exact:true}).click()
  await expect(polygon).toHaveAttribute('points',points!)
  await expect(page.getByRole('row').filter({hasText:'A-02'})).toHaveCount(0)
  await page.getByRole('row').filter({hasText:'A-01'}).getByRole('button',{name:'删除'}).click()
  await page.getByRole('button',{name:'确认',exact:true}).click()
  await expect(page.getByText('地块已关联业务记录，无法删除。')).toBeVisible()
  await page.getByRole('button',{name:'重置',exact:true}).click()
  await page.getByRole('button',{name:/面积（亩）/}).click()
  await expect(page.getByRole('columnheader',{name:/面积（亩）/})).toHaveAttribute('aria-sort','ascending')
  await page.getByRole('button',{name:'新增地块'}).click()
  const dialog=page.getByRole('dialog')
  await dialog.getByLabel('地块编号').fill('A-07')
  await dialog.getByLabel('种植面积（亩）').fill('18.5')
  await dialog.getByLabel('位置',{exact:true}).fill('本地演示苗圃')
  await dialog.getByRole('button',{name:'保存地块'}).click()
  await page.getByLabel('地块搜索').fill('A-07')
  await page.getByRole('button',{name:'查询',exact:true}).click()
  const row=page.getByRole('row').filter({hasText:'A-07'})
  await expect(row).toContainText('18.5')
  await row.getByRole('button',{name:'编辑'}).click()
  await dialog.getByLabel('种植面积（亩）').fill('20')
  await dialog.getByRole('button',{name:'保存地块'}).click()
  await page.getByLabel('地块搜索').fill('A-07')
  await page.getByRole('button',{name:'查询',exact:true}).click()
  await expect(row).toContainText('20')
  await row.getByRole('button',{name:'删除'}).click()
  await page.getByRole('button',{name:'确认',exact:true}).click()
  await expect(row).toHaveCount(0)
})

test('土样报告、人工检测和监控离线状态使用明确来源', async ({page}) => {
  await page.goto('/#/admin/soil')
  await page.getByRole('button',{name:'查看报告'}).click()
  await expect(page.getByRole('dialog').getByText('演示实验室')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button',{name:'新增人工检测记录'}).click()
  const dialog=page.getByRole('dialog',{name:'新增人工检测记录'})
  await dialog.getByLabel('指标').selectOption('ph')
  await dialog.getByLabel('检测数值').fill('15')
  await dialog.getByRole('button',{name:'保存检测记录'}).click()
  await expect(dialog.getByRole('alert')).toContainText('pH 须在 0 至 14 之间。')
  await dialog.getByLabel('检测数值').fill('7.25')
  await dialog.getByRole('button',{name:'保存检测记录'}).click()
  await expect(page.getByRole('row').filter({hasText:'7.25'}).filter({hasText:'人工检测'})).toBeVisible()
  await page.reload()
  await page.getByRole('button',{name:/pH 值/}).click()
  await expect(page.getByRole('row').filter({hasText:'7.25'}).filter({hasText:'人工检测'})).toBeVisible()
  await page.goto('/#/admin/video')
  await page.getByLabel('设备状态').selectOption('offline')
  await page.getByRole('button',{name:'单画面'}).click()
  await expect(page.getByText('设备已离线')).toBeVisible()
  await page.getByRole('button',{name:'历史回放'}).click()
  await expect(page.getByRole('dialog').getByText(/历史录像服务未接入/)).toBeVisible()
})
